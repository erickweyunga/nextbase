import type { Collection, Field } from '@nextbasejs/client';
import { asInput } from './import.ts';

// The TypeScript source of migration files: a collection's JSON is a valid literal,
// and token secrets are left out, so none goes into the repository.

const HEADER = `import { migration } from "@nextbasejs/core";\n`;

/** A collection as a migration file holds it. */
function forFile(collection: Collection): Record<string, unknown> {
  const input = asInput(collection) as Record<string, unknown>;
  if (collection.type === 'auth') {
    input.tokens = Object.fromEntries(
      Object.entries(collection.tokens).map(([type, { duration }]) => [
        type,
        { duration },
      ]),
    );
  }
  return input;
}

export function blankTemplate(): string {
  return `${HEADER}
export default migration({
  async up(app) {
    // app.collections, app.nextbase for records, app.db for SQL.
  },
  async down(app) {
    // Undo up, for revertMigrations().
  },
});
`;
}

export function snapshotTemplate(collections: readonly Collection[]): string {
  return `${HEADER}
// The collections as they were; it changes nothing they all match already.
export default migration({
  async up(app) {
    await app.collections.import(${literal(collections.map(forFile), 4)});
  },
});
`;
}

/**
 * The migration of one change, or undefined when nothing changed. Fields match by
 * id, so migrations of different changes to one collection combine.
 */
export function changeTemplate(
  before: Collection | undefined,
  after: Collection | undefined,
): string | undefined {
  if (!before && after) {
    return file(
      `await app.collections.create(${literal(forFile(after), 4)});`,
      `await app.collections.delete(${JSON.stringify(after.id)});`,
    );
  }
  if (before && !after) {
    return file(
      `await app.collections.delete(${JSON.stringify(before.id)});`,
      `await app.collections.create(${literal(forFile(before), 4)});`,
    );
  }
  if (!before || !after) return undefined;
  const up = diff(before, after);
  if (up.length === 0) return undefined;
  return file(change(before, up), change(after, diff(after, before)));
}

function file(up: string, down: string): string {
  return `${HEADER}
export default migration({
  async up(app) {
    ${up}
  },
  async down(app) {
    ${down}
  },
});
`;
}

function change(collection: Collection, lines: readonly string[]): string {
  return `await app.collections.change<${JSON.stringify(collection.type)}>(${JSON.stringify(collection.id)}, (c) => {
${lines.map((line) => `      ${line}`).join('\n')}
    });`;
}

/** Statements that turn `from` into `to`. */
function diff(from: Collection, to: Collection): string[] {
  const a = forFile(from);
  const b = forFile(to);
  const lines: string[] = [];
  for (const key of Object.keys(b)) {
    if (key === 'fields' || key === 'id') continue;
    const value = b[key];
    const old = a[key];
    if (same(old, value)) continue;
    // Single settings, such as mfa.duration, so changes to others combine.
    assign(lines, `c.${key}`, old, value);
  }
  if (from.type === 'view') return lines;
  const fromFields = new Map(from.fields.map((f, i) => [f.id, { f, i }]));
  const toIds = new Set(to.fields.map((f) => f.id));
  for (const field of from.fields) {
    if (!toIds.has(field.id)) {
      lines.push(`c.fields.removeById(${JSON.stringify(field.id)});`);
    }
  }
  to.fields.forEach((field: Field, i) => {
    const old = fromFields.get(field.id);
    // Order is not migrated: a field that only moved is left where it is.
    if (old && same(old.f, field)) return;
    lines.push(`c.fields.addAt(${i}, ${literal(field, 6)});`);
  });
  return lines;
}

/** Statements that set `path` from `old` to `value`, setting by setting for objects. */
function assign(
  lines: string[],
  path: string,
  old: unknown,
  value: unknown,
): void {
  if (same(old, value)) return;
  if (isPlain(value) && isPlain(old)) {
    for (const key of Object.keys(value)) {
      assign(lines, `${path}.${key}`, old[key], value[key]);
    }
    return;
  }
  lines.push(`${path} = ${literal(value, 6)};`);
}

/** The index of a folder's migrations, sorted by name. */
export function indexTemplate(dir: string, names: readonly string[]): string {
  const sorted = [...names].sort();
  return `// Generated by NextBase: every migration in this folder, in order. Edits are overwritten.
import { migrations } from "@nextbasejs/core";
${sorted.map((name) => `import m${name} from "./${name}";`).join('\n')}

export default migrations({
  dir: ${JSON.stringify(dir)},
  files: {
${sorted.map((name) => `    ${JSON.stringify(name)}: m${name},`).join('\n')}
  },
});
`;
}

function literal(value: unknown, indent: number): string {
  return JSON.stringify(value, null, 2).replace(
    /\n/g,
    `\n${' '.repeat(indent)}`,
  );
}

/** Equal values, whatever order their keys come in, as jsonb keeps its own. */
function same(a: unknown, b: unknown): boolean {
  return JSON.stringify(canonical(a)) === JSON.stringify(canonical(b));
}

function canonical(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonical);
  if (!isPlain(value)) return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, canonical(value[key])]),
  );
}

function isPlain(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}
