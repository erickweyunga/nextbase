import type { Collection, Field } from '@nextbasejs/client';
import { isMultiple } from '../schema/fields.ts';

/** Record types plus a `Collections` map, for `NextBase<Collections>` and `NextBaseClient<Collections>`. */
export function typegen(collections: readonly Collection[]): string {
  const names = new Map<string, string>();
  const used = new Set<string>();
  for (const collection of collections) {
    const base = `${pascal(collection.name)}Record`;
    let name = base;
    for (let i = 2; used.has(name); i++) name = `${base}${i}`;
    used.add(name);
    names.set(collection.id, name);
  }

  const out = [
    '// Generated by `nextbase typegen`. Run it again after changing collections;',
    '// edits here are overwritten.',
    '',
    'import type { RecordModel } from "@nextbasejs/client";',
    '',
  ];
  for (const collection of collections) {
    out.push(
      `/** Records of the ${collection.type} collection \`${collection.name}\`. */`,
      `export interface ${names.get(collection.id)} extends RecordModel {`,
    );
    for (const field of collection.fields) {
      if (field.hidden) continue;
      // A view's columns come from a query, which can produce NULL.
      const type = fieldType(field);
      out.push(
        `  ${field.name}: ${collection.type === 'view' ? `${type} | null` : type};`,
      );
    }
    out.push('}', '');
  }
  out.push(
    '/** Every collection by name, for `NextBase<Collections>` and `NextBaseClient<Collections>`. */',
    'export type Collections = {',
    ...collections.map((c) => `  ${c.name}: ${names.get(c.id)};`),
    '};',
    '',
  );
  return out.join('\n');
}

function fieldType(field: Field): string {
  switch (field.type) {
    case 'number':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'json':
      return 'unknown';
    case 'select':
    case 'file':
    case 'relation':
      return isMultiple(field) ? 'string[]' : 'string';
    default:
      // Text, emails, urls and dates (ISO 8601 strings, "" when blank).
      return 'string';
  }
}

function pascal(name: string): string {
  return name
    .split('_')
    .filter(Boolean)
    .map((part) => part[0]?.toUpperCase() + part.slice(1))
    .join('');
}
